/**
 * Evaluates column detection against the labeled mappings in fixtures/expected.json.
 * Reports per-fixture and overall column-level accuracy, plus downstream checks.
 * Run: npx tsx scripts/eval-import.ts [--write]
 */
import fs from "node:fs";
import path from "node:path";
import { importText } from "../src/lib/import/build";
import { analyze } from "../src/lib/analytics/metrics";
import { selectPersona } from "../src/lib/persona/personas";
import { planStory } from "../src/lib/story/plan";

const REF = "2026-11-24";
const SET = process.argv.includes("--holdout") ? "holdout" : "";
const FIX = path.join(__dirname, "..", "fixtures", SET);
const expected: Record<string, { mapping: Record<string, string>; notes: string }> = JSON.parse(
  fs.readFileSync(path.join(FIX, "expected.json"), "utf8"),
);

let correct = 0;
let total = 0;
let fixturesPerfect = 0;
const lines: string[] = [];
lines.push("| Fixture | Rows | Columns correct | Mistakes | Persona | Slides | Warnings |");
lines.push("|---|---:|---:|---|---|---:|---:|");

for (const [file, exp] of Object.entries(expected)) {
  const text = fs.readFileSync(path.join(FIX, file), "utf8");
  const t0 = performance.now();
  const res = importText(text, { referenceDate: REF });
  const ms = performance.now() - t0;
  const mistakes: string[] = [];
  let ok = 0;
  const cols = Object.entries(exp.mapping);
  for (const [header, want] of cols) {
    const idx = res.headers.findIndex((h) => h.trim() === header.trim());
    const got = idx >= 0 ? (res.mapping.byColumn[idx] ?? "null") : "missing-column";
    const accepted = want.split("|");
    if (accepted.includes(got)) ok++;
    else mistakes.push(`${header}: ${got} (want ${want})`);
  }
  correct += ok;
  total += cols.length;
  if (ok === cols.length) fixturesPerfect++;
  const m = analyze(res, REF);
  const persona = selectPersona(m);
  const plan = planStory({ metrics: m, persona, seed: 1 });
  lines.push(
    `| ${file} | ${res.rows.length} | ${ok}/${cols.length} | ${mistakes.join("; ") || "—"} | ${persona.name} | ${plan.slides.length} | ${res.issues.filter((i) => i.level === "warn").length} |`,
  );
  if (process.argv.includes("--verbose")) {
    console.log(`\n# ${file} (${ms.toFixed(1)} ms)`);
    console.log(res.headers.map((h, i) => `  ${h} → ${res.mapping.byColumn[i]} (${res.mapping.confidence[i]}) ${res.mapping.reasons[i]}`).join("\n"));
    console.log("  format:", res.mapping.dateFormat, res.mapping.dateFormatAmbiguous ? "(ambiguous)" : "");
    console.log("  issues:", res.issues.map((i) => `[${i.level}] ${i.message}`).join("\n          "));
    console.log("  metrics:", JSON.stringify({ total: m.total, companies: m.companies, responded: m.responded, known: m.statusKnown, waiting: m.waiting, aged: m.waitingAged, interviews: m.interviews, offers: m.offers, dated: m.dates?.dated }));
    console.log("  slides:", plan.slides.map((s) => `${s.type}:${s.variant}`).join(", "));
  }
}

const summary = `**Column accuracy: ${correct}/${total} (${((100 * correct) / total).toFixed(1)}%) · fixtures fully correct: ${fixturesPerfect}/${Object.keys(expected).length}**`;
console.log(lines.join("\n"));
console.log("\n" + summary);
if (process.argv.includes("--write")) {
  const out = `# Import accuracy evaluation\n\nGenerated by \`npx tsx scripts/eval-import.ts --write\` against \`fixtures/expected.json\` (hand-labeled column mappings, reference date ${REF}).\nA column counts as correct only when the detected field equals the label (a few columns, like a job-link column, accept either "notes" or "not used").\n\n${summary}\n\n${lines.join("\n")}\n\nCaveat: these fixtures were written by the same author as the detector. They cover the messy cases we know about; real spreadsheets will surface others.\n`;
  fs.mkdirSync(path.join(__dirname, "..", "docs"), { recursive: true });
  fs.writeFileSync(path.join(__dirname, "..", "docs", SET ? "import-eval-holdout.md" : "import-eval.md"), out);
}
